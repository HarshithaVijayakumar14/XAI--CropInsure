/**
 * Translates a single SHAP string or label into the target regional language.
 * Preserves exact numerical values, percentages, and units.
 */
export function translateShapText(text: string, language: string = 'en-IN'): string {
  if (!text || language === 'en-IN' || language === 'en') {
    return text;
  }

  const trimmed = text.trim();

  // 1. Direct dictionary match
  if (SHAP_DICTIONARY[trimmed] && SHAP_DICTIONARY[trimmed][language]) {
    return SHAP_DICTIONARY[trimmed][language];
  }

  // 2. Case where label has prefix or suffix, e.g. "Monsoon Rainfall: impact..."
  if (trimmed.includes(': ')) {
    const [prefix, ...rest] = trimmed.split(': ');
    const suffix = rest.join(': ');
    const transPrefix = SHAP_DICTIONARY[prefix] && SHAP_DICTIONARY[prefix][language] ? SHAP_DICTIONARY[prefix][language] : prefix;
    const transSuffix = translateShapText(suffix, language);
    return `${transPrefix}: ${transSuffix}`;
  }

  // 3. Regex template matchers
  for (const matcher of TEMPLATE_MATCHERS) {
    const match = trimmed.match(matcher.pattern);
    if (match) {
      return matcher.translate(match, language);
    }
  }

  return text;
}

